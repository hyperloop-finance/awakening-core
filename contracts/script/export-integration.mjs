import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const contracts = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const root = resolve(contracts, '..');
const manifest = JSON.parse(readFileSync(resolve(contracts, 'deployments/bsc-testnet-97.json'), 'utf8'));
if (manifest.chainId !== 97) throw Error('Deployment chain mismatch');
// Integration commits may advance HEAD without changing deployed core sources.
execFileSync('git', ['diff', '--quiet', manifest.sourceCommit, '--', 'contracts/src', ':!contracts/src/testnet', 'contracts/foundry.toml'], {cwd: root});
const targets = {
  frontend: resolve(root, 'frontend/src/lib/contracts/generated.ts'),
  backend: resolve(root, 'backend/src/main/resources/contracts'),
};
const names = ['Awakening', 'AwakeningLoans', 'OptionVault', 'AttestedPAT', 'AwakeningSettlement', 'EcrecoverRatifier', 'TestToken', 'TestOracle', 'EventsLib'];
let ts = '// Generated by contracts/script/export-integration.mjs. Do not edit.\n';
ts += `export const deployment = ${JSON.stringify(manifest, null, 2)} as const;\n`;
mkdirSync(resolve(targets.backend, 'abi'), {recursive:true});
for (const name of names) {
  const artifact = JSON.parse(readFileSync(resolve(contracts, `out/${name}.sol/${name}.json`), 'utf8'));
  if (!Array.isArray(artifact.abi)) throw Error(`Missing ABI: ${name}`);
  ts += `export const ${name[0].toLowerCase()+name.slice(1)}Abi = ${JSON.stringify(artifact.abi)} as const;\n`;
  writeFileSync(resolve(targets.backend, `abi/${name}.json`), JSON.stringify(artifact.abi, null, 2)+'\n');
}
writeFileSync(resolve(targets.backend, 'bsc-testnet-97.json'), JSON.stringify(manifest,null,2)+'\n');
writeFileSync(targets.frontend, ts);
console.log(`Exported public deployment + ${names.length} ABIs to frontend/ and backend/.`);
